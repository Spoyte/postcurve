/**
 * Smoke tests for the local EIP-8141 devnet. Run with `../devnet.sh smoke [test...]`.
 *
 *   canonical  self-relay frame tx (VERIFY + SENDER) from user1, sent raw to ethrex
 *              (eth_sendRawTransaction, the canonical mempool), mined
 *   sidecar    the same shape from user2 through the sidecar (eth_sendFrameTransaction),
 *              mined, and the sidecar reports it OnChain
 *   heavy      a wallet whose VERIFY frame burns HEAVY_ITERATIONS * 40 gas (default ~600k):
 *              rejected by both mempools while unstaked; the wallet stakes itself through
 *              the registry; the same tx is sent to the sidecar again (staked), to ethrex,
 *              and finally straight to ethrex_submitPrivilegedFrameTransaction
 *
 * Keys are read from ../data/keys/accounts.json (generated by devnet.sh, gitignored) and are
 * never printed. Frame-tx encoding comes from @forshtat/hegota-support, the library the
 * mempool workshop uses. Exit code 1 if any check fails.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { encodeAbiParameters, encodeFunctionData, decodeFunctionResult, parseAbi, type Address, type Hex } from "viem";
import { privateKeyToAccount } from "viem/accounts";
import { getProfile } from "@forshtat/hegota-support/profiles";
import * as ftx from "@forshtat/hegota-support/tx";
import { rpc, toWire } from "@forshtat/hegota-support/rpc";
import type { FrameTx } from "@forshtat/hegota-support/tx";

const profile = getProfile("ethrex-eip8141-tracer");
const DATA = process.env.DEVNET_DATA ?? join(import.meta.dir, "..", "data");
const meta = JSON.parse(readFileSync(join(DATA, "devnet.json"), "utf8"));
const accounts: { name: string; address: Address; privateKey: Hex }[] = JSON.parse(
  readFileSync(join(DATA, "keys", "accounts.json"), "utf8"),
);
const RPC: string = process.env.DEVNET_RPC_URL ?? meta.rpcUrl;
const SIDECAR: string = process.env.DEVNET_SIDECAR_URL ?? meta.sidecarUrl;
const REGISTRY: Address = meta.stakingRegistry;
const CHAIN_ID = BigInt(meta.chainId);
const MAX_FEE = 2_000_000_000n; // 2 gwei, as in the workshop
const MIN_GAS_PRICE = 2_000_000n; // 0.002 gwei floor for legacy txs
const HEAVY_ITERATIONS = BigInt(process.env.HEAVY_ITERATIONS ?? "15000"); // ~40 gas each
const STAKE_WEI = 20_000_000_000_000_000n; // 0.02 ETH, strictly above minStake 0.01
const UNSTAKE_DELAY = 86_400;

const acct = (name: string) => {
  const a = accounts.find((x) => x.name === name);
  if (!a) throw new Error(`no account ${name} in accounts.json`);
  return a;
};

// --- result bookkeeping -----------------------------------------------------
const results: { name: string; ok: boolean; detail: string; knownGap?: string }[] = [];
const check = (name: string, ok: boolean, detail: string) => {
  results.push({ name, ok, detail });
  console.log(`${ok ? "PASS" : "FAIL"}  ${name}: ${detail}`);
};
/**
 * A check that fails today for a documented reason (README "What is not working yet"). Printed as
 * KNOWN-GAP and not counted as a failure; if it starts passing, it says so loudly.
 */
const checkKnownGap = (name: string, ok: boolean, detail: string, gap: string) => {
  results.push({ name, ok: true, detail, knownGap: ok ? undefined : gap });
  console.log(ok ? `PASS  ${name}: ${detail}\n      (this was a known gap - update devnet/README.md)` : `KNOWN-GAP  ${name}: ${detail}\n      ${gap}`);
};
const STAKED_BUDGET_GAP =
  "The sidecar applies MAX_VERIFY_GAS = 100,000 to every validation prefix, staked or not; it has no " +
  "MAX_VERIFY_GAS_STAKED_ENTITY budget yet. See devnet/README.md.";
const info = (msg: string) => console.log(`      ${msg}`);
const errText = (e: unknown) => (e instanceof Error ? e.message : String(e)).replace(/\s+/g, " ").slice(0, 400);

// --- chain helpers ------------------------------------------------------------
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function waitReceipt(hash: Hex, timeoutMs = 120_000): Promise<any> {
  const end = Date.now() + timeoutMs;
  while (Date.now() < end) {
    const r = await rpc(RPC, "eth_getTransactionReceipt", [hash]);
    if (r) return r;
    await sleep(2000);
  }
  throw new Error(`${hash} not mined within ${timeoutMs / 1000} s`);
}

const receiptOk = (r: any) =>
  r.status === "0x1" && (r.frameReceipts ?? []).every((f: any) => f.status === "0x1");
const describeReceipt = (r: any) =>
  `block ${Number(r.blockNumber)}, gasUsed ${Number(r.gasUsed)}, frames [${(r.frameReceipts ?? [])
    .map((f: any) => f.status)
    .join(",")}]`;

async function nonceOf(addr: Address): Promise<bigint> {
  return BigInt(await rpc(RPC, "eth_getTransactionCount", [addr, "latest"]));
}

async function sidecarStatus(hash: Hex, want: string, timeoutMs = 60_000): Promise<string> {
  const end = Date.now() + timeoutMs;
  let last = "unknown";
  while (Date.now() < end) {
    try {
      last = (await rpc(SIDECAR, "skandha_frameTransactionStatus", [hash])).status;
      if (last === want) return last;
    } catch (e) {
      last = errText(e);
    }
    await sleep(2000);
  }
  return last;
}

/** Legacy CREATE from an EOA, funded through the creation value. Returns the new address. */
async function deploy(fromName: string, initCode: Hex, value: bigint): Promise<Address> {
  const a = privateKeyToAccount(acct(fromName).privateKey);
  // The base fee starts near 1 gwei on a fresh chain and decays toward 7 wei: price off the node.
  const suggested = BigInt(await rpc(RPC, "eth_gasPrice", [])) * 2n;
  const raw = await a.signTransaction({
    chainId: Number(CHAIN_ID),
    nonce: Number(await nonceOf(a.address)),
    to: null,
    value,
    gas: 6_000_000n, // contract creation costs state gas on this chain
    gasPrice: suggested > MIN_GAS_PRICE ? suggested : MIN_GAS_PRICE,
    data: initCode,
    type: "legacy",
  });
  const hash = await rpc(RPC, "eth_sendRawTransaction", [raw]);
  const r = await waitReceipt(hash);
  if (r.status !== "0x1") throw new Error(`deploy ${hash} reverted`);
  return r.contractAddress;
}

// --- frame-tx builders --------------------------------------------------------
const verify = (execution: bigint, data: Hex = "0x") =>
  ftx.frame(profile, "VERIFY", { scope: "EXECUTION_AND_PAYMENT", target: null, execution, data });
const sender = (target: Address, value: bigint, data: Hex = "0x", execution = 50_000n, state = 200_000n) =>
  ftx.frame(profile, "SENDER", { target, execution, state, value, data });

/** `[self_verify, SENDER transfer]`, signed by the EOA itself (the workshop's step 2 shape). */
async function selfRelay(fromName: string, to: Address, value: bigint): Promise<FrameTx> {
  const { address, privateKey } = acct(fromName);
  const tx = ftx.newTx({
    chainId: CHAIN_ID,
    sender: address,
    nonceSeq: await nonceOf(address),
    frames: [verify(30_000n), sender(to, value)],
    signatures: [ftx.secp256k1Placeholder(profile)],
    fees: { maxFeePerGas: MAX_FEE },
  });
  return ftx.signTx(profile, tx, privateKey);
}

/** A tx from a contract wallet that approves unconditionally: ARBITRARY scheme, no signature. */
async function walletTx(wallet: Address, frames: FrameTx["frames"]): Promise<FrameTx> {
  return ftx.newTx({
    chainId: CHAIN_ID,
    sender: wallet,
    nonceSeq: await nonceOf(wallet),
    frames,
    signatures: [{ scheme: ftx.sigScheme(profile, "ARBITRARY"), signer: "0x", msg: "0x", signature: "0x" }],
    fees: { maxFeePerGas: MAX_FEE },
  });
}

/**
 * HeavyWallet runtime (31 bytes, hand-assembled):
 *   if calldata is empty: APPROVE(EXECUTION_AND_PAYMENT) at once;
 *   else loop calldataload(0) times (40 gas per iteration), then APPROVE.
 * No signature check: anyone can spend from it. Devnet test fixture only.
 *
 *   00 CALLDATASIZE ISZERO PUSH1 0x17 JUMPI       ; empty calldata -> approve
 *   05 PUSH1 0 CALLDATALOAD                       ; n
 *   08 JUMPDEST DUP1 ISZERO PUSH1 0x15 JUMPI      ; loop: n == 0 -> end
 *   0e PUSH1 1 SWAP1 SUB PUSH1 0x08 JUMP          ; n -= 1
 *   15 JUMPDEST POP
 *   17 JUMPDEST PUSH1 3 PUSH1 0 PUSH1 0 APPROVE   ; APPROVE(offset 0, len 0, scope 3)
 */
const HEAVY_WALLET_RUNTIME =
  "3615601757600035" + // 00-07
  "5b801560155760019003600856" + // 08-14
  "5b505b600360006000aa"; // 15-1e
if (HEAVY_WALLET_RUNTIME.length !== 0x1f * 2) throw new Error("HeavyWallet runtime must be 31 bytes");
// CODECOPY(0, 0x0c, 0x1f) then RETURN(0, 0x1f): the 12-byte constructor returns the runtime.
const HEAVY_WALLET_INIT = `0x601f600c600039601f6000f3${HEAVY_WALLET_RUNTIME}` as Hex;

const REGISTRY_ABI = parseAbi([
  "function addStake(uint32 unstakeDelaySec) payable",
  "function getDepositInfo(address account) view returns (uint256 stake, uint32 unstakeDelaySec, uint64 withdrawTime)",
]);

async function depositOf(addr: Address) {
  const data = encodeFunctionData({ abi: REGISTRY_ABI, functionName: "getDepositInfo", args: [addr] });
  const out = await rpc(RPC, "eth_call", [{ to: REGISTRY, data }, "latest"]);
  return decodeFunctionResult({ abi: REGISTRY_ABI, functionName: "getDepositInfo", data: out }) as readonly [
    bigint,
    number,
    bigint,
  ];
}

// --- tests ----------------------------------------------------------------------
async function testCanonical() {
  const tx = await selfRelay("user1", acct("dev").address, 1_000_000_000n);
  const raw = ftx.encodeTx(profile, tx);
  try {
    const hash = await rpc(RPC, "eth_sendRawTransaction", [raw]);
    const r = await waitReceipt(hash);
    check("canonical: self-relay frame tx via ethrex", receiptOk(r), `${hash} ${describeReceipt(r)}`);
  } catch (e) {
    check("canonical: self-relay frame tx via ethrex", false, errText(e));
  }
}

async function testSidecar() {
  const tx = await selfRelay("user2", acct("dev").address, 1_000_000_000n);
  try {
    const hash = await rpc(SIDECAR, "eth_sendFrameTransaction", [toWire(tx)]);
    const r = await waitReceipt(hash);
    check("sidecar: self-relay frame tx via eth_sendFrameTransaction", receiptOk(r), `${hash} ${describeReceipt(r)}`);
    const status = await sidecarStatus(hash, "OnChain");
    check("sidecar: status reaches OnChain", status === "OnChain", `skandha_frameTransactionStatus = ${status}`);
  } catch (e) {
    check("sidecar: self-relay frame tx via eth_sendFrameTransaction", false, errText(e));
  }
}

async function testHeavy() {
  const code = await rpc(RPC, "eth_getCode", [REGISTRY, "latest"]);
  if (code === "0x") {
    check("heavy: staking registry deployed", false, `no code at ${REGISTRY}; run ./devnet.sh predeploy`);
    return;
  }
  const wallet = await deploy("user3", HEAVY_WALLET_INIT, 1_000_000_000_000_000_000n); // 1 ETH
  info(`HeavyWallet deployed at ${wallet} (funded with 1 ETH through CREATE value)`);
  const recipient = acct("user3").address;
  const verifyGas = HEAVY_ITERATIONS * 40n + 25_000n;
  const heavyData = encodeAbiParameters([{ type: "uint256" }], [HEAVY_ITERATIONS]);
  const heavyTx = () => walletTx(wallet, [verify(verifyGas, heavyData), sender(recipient, 1n)]);
  info(`heavy VERIFY frame: ${HEAVY_ITERATIONS} iterations, execution limit ${verifyGas}`);

  // Measure what the VERIFY frame really burns (ethrex dry run, no mempool rules applied).
  try {
    const sim = await rpc(RPC, "ethrex_simulateFrameTransaction", [ftx.encodeTx(profile, await heavyTx()), "latest"]);
    const { erc7562Trace: _trace, ...summary } = sim ?? {};
    info(`ethrex_simulateFrameTransaction: ${JSON.stringify(summary).slice(0, 400)}`);
  } catch (e) {
    info(`ethrex_simulateFrameTransaction failed: ${errText(e)}`);
  }

  // 1. Unstaked: both mempools should refuse it.
  try {
    const h = await rpc(SIDECAR, "eth_sendFrameTransaction", [toWire(await heavyTx())]);
    check("heavy: unstaked tx rejected by sidecar", false, `admitted as ${h} (expected a rejection)`);
    await waitReceipt(h).catch(() => undefined);
  } catch (e) {
    check("heavy: unstaked tx rejected by sidecar", true, errText(e));
  }

  // 2. Stake the wallet: its own SENDER frame calls addStake, so msg.sender is the wallet.
  const stakeData = encodeFunctionData({ abi: REGISTRY_ABI, functionName: "addStake", args: [UNSTAKE_DELAY] });
  try {
    const stakeTx = await walletTx(wallet, [verify(30_000n), sender(REGISTRY, STAKE_WEI, stakeData, 150_000n, 300_000n)]);
    const h = await rpc(SIDECAR, "eth_sendFrameTransaction", [toWire(stakeTx)]);
    const r = await waitReceipt(h);
    const [stake, delay, withdrawTime] = await depositOf(wallet);
    check(
      "heavy: wallet staked itself via the sidecar",
      receiptOk(r) && stake === STAKE_WEI && delay === UNSTAKE_DELAY && withdrawTime === 0n,
      `${h} ${describeReceipt(r)}; registry stake=${stake} delay=${delay}`,
    );
  } catch (e) {
    check("heavy: wallet staked itself via the sidecar", false, errText(e));
    return;
  }

  // 3. Staked, through the sidecar: the case postcurve needs.
  try {
    const h = await rpc(SIDECAR, "eth_sendFrameTransaction", [toWire(await heavyTx())]);
    const r = await waitReceipt(h);
    checkKnownGap("heavy: STAKED heavy-validation tx admitted and mined by sidecar", receiptOk(r), `${h} ${describeReceipt(r)}`, STAKED_BUDGET_GAP);
  } catch (e) {
    checkKnownGap("heavy: STAKED heavy-validation tx admitted and mined by sidecar", false, errText(e), STAKED_BUDGET_GAP);
  }

  // 4. Staked, canonical mempool: expected to stay rejected (MAX_VERIFY_GAS = 100k).
  try {
    const h = await rpc(RPC, "eth_sendRawTransaction", [ftx.encodeTx(profile, await heavyTx())]);
    const r = await waitReceipt(h);
    info(`canonical mempool admitted the heavy tx: ${h} ${describeReceipt(r)}`);
  } catch (e) {
    info(`canonical mempool (ethrex) rejected the heavy tx, as expected: ${errText(e)}`);
  }

  // 5. Bypass both mempools: does block execution itself accept a heavy VERIFY frame?
  try {
    const tx = await heavyTx();
    const raw = ftx.encodeTx(profile, tx);
    const h = ftx.txHash(profile, tx);
    await rpc(RPC, "ethrex_submitPrivilegedFrameTransaction", [raw]);
    const r = await waitReceipt(h, 60_000);
    check("heavy: tx mined via ethrex_submitPrivilegedFrameTransaction (no mempool)", receiptOk(r), `${h} ${describeReceipt(r)}`);
  } catch (e) {
    check("heavy: tx mined via ethrex_submitPrivilegedFrameTransaction (no mempool)", false, errText(e));
  }
}

// --- main ---------------------------------------------------------------------------
const tests: Record<string, () => Promise<void>> = { canonical: testCanonical, sidecar: testSidecar, heavy: testHeavy };
const wanted = process.argv.slice(2).filter((a) => a !== "all");
const run = wanted.length ? wanted : Object.keys(tests);

const head = await rpc(RPC, "eth_getBlockByNumber", ["latest", false]);
// Two slots of margin past activation, as in `devnet.sh wait-hegota` (see README, Gotchas).
const ready = meta.hegotaTime + 12;
if (Number(head.timestamp) < ready) {
  console.error(`Hegota is not settled yet (${ready - Number(head.timestamp)} s to go); run ./devnet.sh wait-hegota`);
  process.exit(1);
}
console.log(`devnet: rpc ${RPC}, sidecar ${SIDECAR}, head block ${Number(head.number)}`);
for (const name of run) {
  if (!tests[name]) throw new Error(`unknown test ${name}; one of ${Object.keys(tests).join(", ")}`);
  console.log(`--- ${name}`);
  await tests[name]();
}
const failed = results.filter((r) => !r.ok);
const gaps = results.filter((r) => r.knownGap);
console.log(
  `\n${results.length - failed.length - gaps.length}/${results.length} checks passed` +
    (gaps.length ? `, ${gaps.length} known gap(s)` : "") +
    (failed.length ? `, ${failed.length} FAILED` : ""),
);
process.exit(failed.length ? 1 : 0);
